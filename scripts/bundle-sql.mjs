// Concatenates the migrations and seed into supabase/setup_all.sql for one paste into the SQL editor.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
const files = ['migrations/0001_schema.sql', 'migrations/0002_functions.sql', 'migrations/0003_rls.sql', 'migrations/0004_storage_realtime.sql', 'seed.sql', 'migrations/0005_sessions_plus.sql', 'migrations/0006_support.sql', 'migrations/0007_session_covers.sql']
const out = ['-- FarmLink: full database setup (generated by npm run db:bundle). Paste into the Supabase SQL editor and run once.\n']
for (const f of files) out.push(`\n-- ==================== ${f} ====================\n`, readFileSync(`supabase/${f}`, 'utf8'))
writeFileSync('supabase/setup_all.sql', out.join(''))
console.log('wrote supabase/setup_all.sql')
